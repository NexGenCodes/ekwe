#!/usr/bin/env node

/**
 * Record a checksum for every migration currently in the Supabase directory.
 *
 * Why this exists: the Supabase CLI identifies a migration by the version in its
 * filename and records only that version. It stores no checksum of the file's
 * contents, so it cannot tell that a migration which is already applied to
 * production has since been edited. That is not hypothetical here:
 * `20260926010000_add_history_origin.sql` was changed after it had been applied,
 * which is why `history.source_app` drifted between the migration and the live
 * database and needed a forward fix.
 *
 * This script writes the hash of each file to `checksums.json` next to the
 * migrations. `check-migrations.mjs` then fails if any locked file is edited or
 * deleted, which is the whole point of locking.
 *
 * Run it after applying migrations:
 *
 *     pnpm db:migrate
 *
 * `db:migrate` chains this automatically, so a local push refreshes the lock
 * with no extra step. A migration that is edited after being pushed is exactly
 * the case the lock is meant to catch — re-running this script to accept an
 * edited file is a deliberate act that shows up as a lockfile diff in review.
 */

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

import {
  ALLOWED_LEGACY,
  CONVENTION,
  MIGRATIONS_DIR,
} from "./check-migrations.mjs";

const CHECKSUMS_FILE = join(MIGRATIONS_DIR, "checksums.json");

function isMigration(name) {
  return (
    name.endsWith(".sql") && (CONVENTION.test(name) || ALLOWED_LEGACY.has(name))
  );
}

export function buildLockfile(filenames) {
  const files = {};
  for (const name of filenames.filter(isMigration).sort()) {
    const contents = readFileSync(join(MIGRATIONS_DIR, name));
    files[name] = createHash("sha256").update(contents).digest("hex");
  }
  return {
    _comment:
      "sha256 of each migration that has been applied. Generated by " +
      "scripts/lock-migrations.mjs; verified by scripts/check-migrations.mjs. " +
      "Do not hand-edit, and do not re-run to silence an integrity failure — a " +
      "modified migration needs a new forward migration, not a new hash.",
    algorithm: "sha256",
    files,
  };
}

function main() {
  const lockfile = buildLockfile(readdirSync(MIGRATIONS_DIR));
  const count = Object.keys(lockfile.files).length;
  writeFileSync(CHECKSUMS_FILE, `${JSON.stringify(lockfile, null, 2)}\n`);
  console.log(`Locked ${count} migration(s) -> ${resolve(CHECKSUMS_FILE)}`);
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) {
  main();
}
