"use strict";


const APP_GROUP_ID = "group.com.ekwe.app";


function swiftName(key) {
  const segments = key.replace(/^EXPO_PUBLIC_/, "").split("_");
  return segments
    .map((seg, i) => {
      if (seg === "URL") return "URL";
      const lower = seg.toLowerCase();
      if (i === 0) return lower;
      return lower[0].toUpperCase() + lower.slice(1);
    })
    .join("");
}

function escapeSwiftString(value) {
  return value.replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}


function typedDecl(name, value) {
  if (/^https?:\/\/\S+$/i.test(value)) {
    return `    static let ${name}: URL = URL(string: "${escapeSwiftString(value)}")!`;
  }
  if (/^[-+]?\d+$/.test(value)) {
    return `    static let ${name}: Int = ${value}`;
  }
  if (/^[-+]?\d*\.\d+$/.test(value)) {
    return `    static let ${name}: Double = ${value}`;
  }
  if (/^(true|false)$/i.test(value)) {
    return `    static let ${name}: Bool = ${value.toLowerCase()}`;
  }
  return `    static let ${name}: String = "${escapeSwiftString(value)}"`;
}

function generateEchoEnvironment(envVars, maxAudioBytes) {
  const publicKeys = Object.keys(envVars)
    .filter((k) => k.startsWith("EXPO_PUBLIC_"))
    .sort();

  const lines = publicKeys.map((k) => typedDecl(swiftName(k), envVars[k]));

  return `// GENERATED by native-env codegen (scripts/tokens/native-env.cjs) — DO NOT EDIT.
// Source of truth: Expo env (EXPO_PUBLIC_* keys) + packages/shared/src/plans.ts.
// Regenerated on every \`expo prebuild\` via app.plugin.js, and on demand via
// \`pnpm gen:env\`. Only publishable EXPO_PUBLIC_* values are emitted.
import Foundation

@available(iOS 16.4, *)
enum EchoEnvironment {
    /// Root of the Ekwe Cloudflare Worker (\`transcribe\` / \`translate\` endpoints).
${lines.join("\n")}

    static let appGroupID: String = "${APP_GROUP_ID}"

    /// Canonical, product-aware upload cap — matches the app's MAX_AUDIO_BYTES
    /// so Pro users can transcribe 26 MB voice notes in the share sheet too.
    static let maxAudioBytes: Int = ${maxAudioBytes}
}
`;
}

module.exports = { APP_GROUP_ID, generateEchoEnvironment, swiftName };