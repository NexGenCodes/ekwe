-- Drop the broken `notify_new_user` auth-users trigger + function.
--
-- A `notify_new_user()` function was applied directly to the hosted database
-- (never via a migration) and wired as an AFTER INSERT trigger on auth.users:
--
--   CREATE TRIGGER on_auth_user_created
--     AFTER INSERT ON auth.users
--     FOR EACH ROW
--     EXECUTE FUNCTION notify_new_user()
--
-- It calls `supabase_functions.http_request(...)` (with an embedded
-- authorization secret) to a `send-welcome-email` edge function. When that
-- HTTP call fails or the SECURITY DEFINER function throws, the AFTER INSERT
-- trigger aborts the whole insert, so Supabase Auth returns:
--
--   {"code":500,"error_code":"unexpected_failure",
--    "msg":"Database error saving new user", ...}
--
-- breaking OTP/email sign-up for EVERY new user. This is the same failure
-- mode the (already-removed) `send_welcome_email` trigger had.
--
-- The sanctioned welcome-email mechanism is a Supabase Dashboard Database
-- Webhook on auth.users INSERT targeting the edge function with its own
-- secret header — not a blocking DB trigger. See 20260814010000 for the
-- full rationale.
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
DROP FUNCTION IF EXISTS public.notify_new_user();
