const fs = require("node:fs");
const path = require("node:path");
const {
  withAppBuildGradle,
  withDangerousMod,
  withInfoPlist,
} = require("@expo/config-plugins");

// Wire release APK signing to a gitignored android/keystore.properties file
// (written by CI from the ANDROID_KEYSTORE_B64 secret) instead of the
// hard-coded debug keystore that the RN template ships in the release
// buildType. Falls back to debug signing when no keystore.properties exists
// (local dev, or a release without the secret configured), so builds never
// break just because signing isn't set up.
function withReleaseSigning(config) {
  return withAppBuildGradle(config, (cfg) => {
    let contents = cfg.modResults.contents;

    if (!contents.includes("keystoreProperties['storeFile']")) {
      const signingIdx = contents.indexOf("signingConfigs {");
      const buildTypesIdx = contents.indexOf("buildTypes {");
      if (signingIdx === -1 || buildTypesIdx === -1)
        throw new Error(
          "Could not find signingConfigs/buildTypes blocks in app/build.gradle",
        );

      const loaderSrc = `

// Load keystore.properties from apps/mobile/secrets/ (survives prebuild, which
// wipes android/), falling back to the legacy android/ location; see app.config.js.
def secretsKeystorePropertiesFile = rootProject.file("../secrets/keystore.properties")
def keystorePropertiesFile = secretsKeystorePropertiesFile.exists()
    ? secretsKeystorePropertiesFile
    : rootProject.file("keystore.properties")
def keystoreProperties = new Properties()
if (keystorePropertiesFile.exists()) {
    keystoreProperties.load(new FileInputStream(keystorePropertiesFile))
}
`;
      contents =
        contents.slice(0, signingIdx) + loaderSrc + contents.slice(signingIdx);

      const releaseSigning = `
    release {
        if (keystorePropertiesFile.exists()) {
            storeFile file(keystoreProperties['storeFile'])
            storePassword keystoreProperties['storePassword']
            keyAlias keystoreProperties['keyAlias']
            keyPassword keystoreProperties['keyPassword']
        }
    }`;
      const blockStart = contents.indexOf("signingConfigs {");
      const blockEnd = contents.indexOf("buildTypes {");
      const blockText = contents.slice(blockStart, blockEnd);
      const closes = [...blockText.matchAll(/\n\s*}/g)];
      const lastClose = closes[closes.length - 1];
      if (!lastClose)
        throw new Error(
          "Could not find signingConfigs closing brace in app/build.gradle",
        );
      const pos = blockStart + lastClose.index;
      contents = contents.slice(0, pos) + releaseSigning + contents.slice(pos);
    }

    if (!contents.includes("signingConfig keystorePropertiesFile.exists()")) {
      const marker = "signingConfig signingConfigs.debug";
      const replacement =
        "signingConfig keystorePropertiesFile.exists() ? signingConfigs.release : signingConfigs.debug";
      const idx = contents.lastIndexOf(marker);
      if (idx === -1)
        throw new Error(
          "Could not find release signingConfig in app/build.gradle",
        );
      contents =
        contents.slice(0, idx) +
        replacement +
        contents.slice(idx + marker.length);
    }

    cfg.modResults.contents = contents;
    return cfg;
  });
}

// android/ and ios/ are gitignored and regenerated by `expo prebuild`, so
// native resource tweaks must be reapplied as config plugins — never by
// editing the generated folder directly.

/**
 * Silences `sentry.options.json not found in app root` on every Android build.
 *
 * `@sentry/react-native`'s sentry.gradle.kts registers a
 * `copySentryJsonConfiguration` task that looks for a `sentry.options.json`
 * next to `android/` and warns when it is absent. That file is only for
 * overriding options that cannot be set from `Sentry.init` — this app is
 * configured through the Expo config plugin and `EXPO_PUBLIC_SENTRY_DSN`
 * (see `src/utils/logger.ts`), so there is nothing for it to copy. The task
 * is skipped through `shouldCopySentryOptionsFile`, the override point the
 * gradle script documents; it must be a Closure because the script casts
 * that extra property to one before calling it.
 */
function withSentryOptionsFileCopyDisabled(config) {
  return withAppBuildGradle(config, (cfg) => {
    const marker = "sentry.gradle.kts";
    if (!cfg.modResults.contents.includes(marker)) {
      throw new Error(
        "Could not find the sentry.gradle.kts apply in app/build.gradle",
      );
    }
    if (cfg.modResults.contents.includes("shouldCopySentryOptionsFile")) {
      return cfg;
    }

    const contents = cfg.modResults.contents;
    const lineEnd = contents.indexOf("\n", contents.indexOf(marker));
    cfg.modResults.contents =
      contents.slice(0, lineEnd + 1) +
      "\n// Sentry is configured from app.config.js + EXPO_PUBLIC_SENTRY_DSN, so there\n" +
      "// is no sentry.options.json to copy. See withSentryOptionsFileCopyDisabled.\n" +
      "project.ext.shouldCopySentryOptionsFile = { -> false }\n" +
      contents.slice(lineEnd + 1);
    return cfg;
  });
}

/**
 * Makes the Android system (status + navigation) bars use the correct icon
 * color for the active theme: dark icons on light windows, light icons on
 * dark. expo-status-bar's runtime flag can be reset (screen transitions,
 * keyboard, cold start), and without a native `windowLightStatusBar` baseline
 * Android falls back to white icons — unreadable on a light background. The
 * value is a `@bool` resource so the values/ (light) and values-night/ (dark)
 * qualifiers pick the right state automatically at build time.
 */
function withGoogleIosUrlScheme(config) {
  const iosClientId = process.env.EXPO_PUBLIC_GOOGLE_IOS_CLIENT_ID;
  if (!iosClientId) return config;

  const urlScheme = `com.googleusercontent.apps.${iosClientId}`;
  return withInfoPlist(config, (cfg) => {
    const urlTypes = cfg.modResults.CFBundleURLTypes ?? [];
    const hasScheme = urlTypes.some(({ CFBundleURLSchemes }) =>
      CFBundleURLSchemes?.includes(urlScheme),
    );
    if (!hasScheme) {
      urlTypes.push({ CFBundleURLSchemes: [urlScheme] });
    }
    cfg.modResults.CFBundleURLTypes = urlTypes;
    return cfg;
  });
}

function withGoogleAndroidWebClientId(config) {
  const webClientId = process.env.EXPO_PUBLIC_GOOGLE_WEB_CLIENT_ID;
  if (!webClientId) return config;

  return withDangerousMod(config, [
    "android",
    (cfg) => {
      const googleServicesPath = path.join(__dirname, "google-services.json");
      const googleServices = JSON.parse(
        fs.readFileSync(googleServicesPath, "utf8"),
      );
      const hasWebClient = googleServices.client.some((client) =>
        client.oauth_client?.some(({ client_type }) => client_type === 3),
      );
      if (hasWebClient) return cfg;

      const stringsPath = path.join(
        cfg.modRequest.platformProjectRoot,
        "app",
        "src",
        "main",
        "res",
        "values",
        "strings.xml",
      );
      let strings = fs.readFileSync(stringsPath, "utf8");
      if (!strings.includes('name="default_web_client_id"')) {
        strings = strings.replace(
          "</resources>",
          `  <string name="default_web_client_id">${webClientId}</string>\n</resources>`,
        );
        fs.writeFileSync(stringsPath, strings);
      }
      return cfg;
    },
  ]);
}

function withStatusBarTheme(config) {
  return withDangerousMod(config, [
    "android",
    (cfg) => {
      const resDir = path.join(
        cfg.modRequest.platformProjectRoot,
        "app",
        "src",
        "main",
        "res",
      );

      const stylesPath = path.join(resDir, "values", "styles.xml");
      if (fs.existsSync(stylesPath)) {
        let styles = fs.readFileSync(stylesPath, "utf8");
        if (!styles.includes("android:windowLightStatusBar")) {
          styles = styles.replace(
            /<item name="android:windowBackground">@color\/activityBackground<\/item>/,
            '<item name="android:windowLightStatusBar">@bool/windowIsLight</item>\n' +
              '    <item name="android:windowLightNavigationBar">@bool/windowIsLight</item>\n' +
              '    <item name="android:windowBackground">@color/activityBackground</item>',
          );
          fs.writeFileSync(stylesPath, styles);
        }
      }

      fs.mkdirSync(path.join(resDir, "values"), { recursive: true });
      fs.writeFileSync(
        path.join(resDir, "values", "bools.xml"),
        '<resources>\n  <bool name="windowIsLight">true</bool>\n</resources>\n',
      );

      fs.mkdirSync(path.join(resDir, "values-night"), { recursive: true });
      fs.writeFileSync(
        path.join(resDir, "values-night", "bools.xml"),
        '<resources>\n  <bool name="windowIsLight">false</bool>\n</resources>\n',
      );

      return cfg;
    },
  ]);
}
function readSharedVersion() {
  const versionTsPath = path.resolve(
    __dirname,
    "../../packages/shared/src/version.ts",
  );
  const content = fs.readFileSync(versionTsPath, "utf8");
  const version = content.match(/APP_VERSION\s*=\s*"([^"]+)"/)?.[1];
  const versionCode = content.match(/APP_VERSION_CODE\s*=\s*(\d+)/)?.[1];
  if (!version || !versionCode) {
    throw new Error(
      `Could not parse APP_VERSION/APP_VERSION_CODE from ${versionTsPath}`,
    );
  }
  return { version, versionCode: Number(versionCode) };
}

module.exports = ({ config }) => {
  // Version lives in packages/shared/src/version.ts (single source of truth).
  const { version, versionCode } = readSharedVersion();

  // Dev builds: build only for the connected device's CPU architecture.
  // Pass the detected arch via EXPO_PUBLIC_DEV_ARCH (set by the android script).
  // Production releases: build all active ABIs to support all Android devices.
  const isProduction =
    process.env.APP_ENV === "production" ||
    process.env.EAS_BUILD === "true" ||
    process.env.NODE_ENV === "production";

  const reactNativeArchitectures = isProduction
    ? "armeabi-v7a,arm64-v8a"
    : process.env.EXPO_PUBLIC_DEV_ARCH || "arm64-v8a";

  // Compress native libraries (.so) in APK builds for a smaller download.
  // RN 0.73+ ships .so files uncompressed (extractNativeLibs=false) for direct
  // mmap — faster startup but larger APK. Keep that for the Play Store AAB
  // (per-ABI delivery, mmap matters); enable legacy packaging everywhere else
  // (preview/internal APK, local builds) to shrink the APK.
  const isPlayStoreBuild = process.env.EAS_BUILD_PROFILE === "production";
  const useLegacyPackaging = !isPlayStoreBuild;

  const plugins = (config.plugins || []).map((plugin) => {
    if (Array.isArray(plugin) && plugin[0] === "expo-build-properties") {
      // Preserve every option that app.json declares for this plugin
      // (minify, shrinkResources, extraProguardRules, buildArchs, png
      // crunch, ...) and only override the fields this file owns.
      const previous = plugin[1] || {};
      return [
        "expo-build-properties",
        {
          ...previous,
          android: {
            ...(previous.android || {}),
            compileSdkVersion: 36,
            targetSdkVersion: 36,
            minSdkVersion: 24,
            ndkVersion: "27.1.12297006",
            useLegacyPackaging,
            reactNativeArchitectures,
          },
        },
      ];
    }
    return plugin;
  });

  plugins.push("@react-native-google-signin/google-signin");
  plugins.push(withGoogleIosUrlScheme);
  plugins.push(withGoogleAndroidWebClientId);

  plugins.push("expo-asset");

  plugins.push(withStatusBarTheme);

  plugins.push(withReleaseSigning);

  const sentryIndex = plugins.findIndex(
    (p) =>
      p === "@sentry/react-native/expo" ||
      (Array.isArray(p) && p[0] === "@sentry/react-native/expo"),
  );

  if (sentryIndex !== -1) {
    // `withAppBuildGradle` mods run in reverse registration order: the last
    // plugin in the array is applied first. This one edits the line Sentry's
    // plugin injects, so it has to be registered *before* it — pushed at the
    // end it ran first, found no `sentry.gradle.kts` apply, and failed prebuild.
    plugins.splice(sentryIndex, 0, withSentryOptionsFileCopyDisabled);
    plugins[sentryIndex + 1] = [
      "@sentry/react-native/expo",
      {
        url: "https://sentry.io/",
        organization: process.env.SENTRY_ORG,
        project: process.env.SENTRY_PROJECT,
        // Wires the Sentry Android Gradle Plugin into prebuild so the R8/ProGuard
        // mapping.txt is auto-uploaded on release builds. Without it, native stack
        // traces stay obfuscated once minify (R8) is enabled. Requires
        // SENTRY_AUTH_TOKEN to be set during the release build.
        experimental_android: {
          enableAndroidGradlePlugin: true,
          includeProguardMapping: true,
          autoUploadProguardMapping: true,
        },
      },
    ];
  }

  return {
    ...config,
    version,
    android: {
      ...config.android,
      versionCode,
    },
    ios: {
      ...config.ios,
      buildNumber: String(versionCode),
    },
    plugins,
  };
};
